import com.svenruppert.ddi.DIContainer;

/**
 * Thin static facade over the global {@link DIContainer}'s implementing-class
 * resolver. State now lives entirely in the container; this class keeps its
 * public static API for backwards compatibility with existing callers and
 * tests that worked against the pre-2.3 static singleton.
 */
public final class ImplementingClassResolver {

  private ImplementingClassResolver() {
  }

  public static void clearCache() {
    DIContainer.global().clearImplResolverCache();
  }

  public static <I> Class<? extends I> resolve(Class<I> interf) {
    return DIContainer.global().resolveImplementingClass(interf);
  }
}
